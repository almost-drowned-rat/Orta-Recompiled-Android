/* launcher/main.c -- "Panzer Dragoon Orta Recomp.exe", the one file a player downloads: the
 * toolkit's launcher (src/launcher) with Orta's names, versions and icon. The release script (tools/release.ps1)
 * appends the payload to the built exe. Model: THPS 2X launcher/main.c.
 *
 * Since 2026-11-05 (maintainer: another port's launcher design, two lines for Orta): a fresh download started without
 * arguments opens the setup window (setup_win32.c: disc image, install folder, Go -> Play); it copies this exe into
 * the install folder and runs the copy there with --image / --no-start / --setup-parent. Every other start - an
 * installed folder (data\build\stamp.txt), a game\ folder the player filled by hand, --repair, the setup's copy -
 * goes to the toolkit's launcher as before, with the progress in the same look. No Vulkan 1.3 device: an apology
 * box before anything else (maintainer 2026-11-04; ORTA.exe asks the same).
 *
 * The Linux launcher (AppImage usr/bin/panzer-dragoon-orta-recomp) is the same file, see below. */

/* Linux (v1.1.0, AppImage): no setup window - the player puts the .AppImage into a folder of its own and the disc image
 * (or the extracted disc) into game/ beside it, as the README says; every start goes to the toolkit's launcher, which
 * shows its own progress window, builds once into the folder beside the .AppImage and then starts ORTA. The Vulkan 1.3
 * check with the apology is the same (src/vk_check.c), its box an SDL message box. */

#include "launcher.h"
#include "port_icon.h"          /* g_port_icon_bmp: assets/icon_64.bmp, generated by CMake */
#include "vk_check.h"
#include "platform/host_paths.h" /* xbox_host_root: the writable folder (beside the .AppImage, or the exe's folder) */
#ifdef _WIN32
#include "setup_win32.h"
#endif

#include <SDL3/SDL.h>
#include <SDL3/SDL_main.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#ifndef _WIN32
/* 1 when a Vulkan 1.3 device is there, else the apology box (not with RECOMP_NO_DIALOGS=1) and 0 */
static int orta_vk_gate(void)
{
    char found[1024], msg[1600];
    const char *nd = getenv("RECOMP_NO_DIALOGS");
    if (orta_vk_check(found, sizeof found))
        return 1;
    orta_vk_message(msg, sizeof msg, found);
    fprintf(stderr, "%s\n", msg);
    if (!(nd && *nd == '1'))
        SDL_ShowSimpleMessageBox(SDL_MESSAGEBOX_ERROR, "Panzer Dragoon Orta Recomp", msg, NULL);
    return 0;
}
#endif

/* 1 when the install folder is (being) used as a game folder already: then the toolkit's launcher takes over */
static int folder_in_use(void)
{
    const char *base = xbox_host_root();   /* = SDL_GetBasePath() on Windows; beside the .AppImage on Linux */
    char p[1024];
    SDL_PathInfo info;
    if (!base || !*base)
        return 1;
    snprintf(p, sizeof p, "%sdata/build/stamp.txt", base);
    if (SDL_GetPathInfo(p, &info))
        return 1;                       /* installed: start the game */
    snprintf(p, sizeof p, "%sgame/default.xbe", base);
    if (SDL_GetPathInfo(p, &info))
        return 1;                       /* extracted disc files put into game\ by hand */
    snprintf(p, sizeof p, "%sgame", base);
    if (SDL_GetPathInfo(p, &info) && info.type == SDL_PATHTYPE_DIRECTORY) {
        /* an .iso put into game\ by hand (the toolkit's way): any file other than README.txt counts */
        char **files = SDL_GlobDirectory(p, "*", 0, NULL);
        int used = 0, i;
        for (i = 0; files && files[i]; i++)
            if (SDL_strcasecmp(files[i], "README.txt") != 0)
                used = 1;
        SDL_free(files);
        if (used)
            return 1;
    }
    return 0;
}

int main(int argc, char **argv)
{
    /* the supported versions (CLAUDE.md "Title decisions"; src/main.c orta_game_setup) */
    static const xr_game_version versions[] = {
        { "Europe", "57213FF35A19807DEF664F9018CC2923815DFA1F" },
    };
    XrLauncherConfig c = {
        "Panzer Dragoon Orta",
        "Panzer Dragoon Orta (Europe)",
        "Panzer Dragoon Orta Recomp",
        "ORTA.exe",
        0x4947002Bu,
        versions,
        sizeof versions / sizeof versions[0],
        g_port_icon_bmp,
        sizeof g_port_icon_bmp,
        "panzer-dragoon-orta-recomp",   /* AppImage: usr/share/<slug>/tools (packaging/linux, tools/release_linux.sh) */
    };
    int parent = 0;

#ifdef _WIN32
    {
        int i;
        for (i = 1; i + 1 < argc; i++)
            if (!strcmp(argv[i], "--setup-parent")) {
                orta_setup_set_parent(strtoull(argv[i + 1], NULL, 10));
                parent = 1;
            }
    }
    if (argc <= 1 && !folder_in_use())
        return orta_setup_window();
#endif
    /* the toolkit's launcher; an installed folder only starts ORTA.exe, which checks Vulkan itself */
    if (!parent && !folder_in_use() && !orta_vk_gate())
        return 1;
    return xr_launcher_main(&c, argc, argv);
}
